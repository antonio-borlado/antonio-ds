// Generates one module per icon library from the curated DS map (scripts/icon-map.mjs).
// Each module registers its set on a global registry and imports nothing, so CDN bundles stay self-contained.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS } from './icon-map.mjs';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/icons/generated');

const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`));
const SETS = [
  {
    name: 'lucide',
    dir: join(pkgDir('lucide-static'), 'icons'),
    attrs: 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"',
    license: 'Lucide (ISC) — https://lucide.dev',
  },
  {
    name: 'heroicons',
    dir: join(pkgDir('heroicons'), '24/outline'),
    attrs: 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5"',
    license: 'Heroicons (MIT) — https://heroicons.com',
  },
  {
    name: 'material',
    dir: join(pkgDir('@material-symbols/svg-400'), 'outlined'),
    attrs: 'viewBox="0 -960 960 960" fill="currentColor"',
    license: 'Material Symbols (Apache-2.0) — https://fonts.google.com/icons',
  },
];

// Keep only the shapes inside <svg>; the root attributes are normalised per set above.
const inner = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();

mkdirSync(OUT, { recursive: true });
for (const [i, set] of SETS.entries()) {
  const icons = Object.fromEntries(ICONS.map((row) => [row[0], inner(readFileSync(join(set.dir, `${row[i + 1]}.svg`), 'utf8'))]));
  writeFileSync(
    join(OUT, `${set.name}.ts`),
    `// Generated by scripts/build-icons.mjs — do not edit. Icons: ${set.license}
const icons: Record<string, string> = ${JSON.stringify(icons, null, 2)};
const registry = ((globalThis as any).__dsIcons ??= { sets: {}, listeners: new Set() });
registry.sets[${JSON.stringify(set.name)}] = { attrs: ${JSON.stringify(set.attrs)}, icons };
registry.listeners.forEach((notify: (set: string) => void) => notify(${JSON.stringify(set.name)}));
export {};
`,
  );
}
writeFileSync(
  join(OUT, 'names.ts'),
  `// Generated by scripts/build-icons.mjs — do not edit.
export const iconNames = ${JSON.stringify(ICONS.map((r) => r[0]))} as const;
export type IconName = (typeof iconNames)[number];
export const iconSets = ${JSON.stringify(SETS.map((s) => s.name))} as const;
export type IconSet = (typeof iconSets)[number];
`,
);
console.log(`icons: ${ICONS.length} icons × ${SETS.length} sets → ${OUT}`);
